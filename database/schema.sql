-- database/schema.sql
-- Database Schema for SGP-II AI-Augmented Decision-Support Sandbox
-- Compatible with SQLite (local development) and PostgreSQL (cloud serverless, e.g. Neon)

-- Table to cache company fundamentals from weekly screeners
CREATE TABLE IF NOT EXISTS company_fundamentals (
    ticker TEXT PRIMARY KEY,
    pe_ratio REAL,
    debt_to_equity REAL,
    operating_margin REAL,
    roe REAL,
    is_healthy INTEGER DEFAULT 1, -- 1 for True, 0 for False (standard SQLite boolean)
    cautionary_remark TEXT, -- Explanatory remark when high debt is qualified by strong future demand
    last_updated DATETIME DEFAULT CURRENT_TIMESTAMP
);

-- Table to store daily news sentiment calculated by pre-market workflow (both macro and per-ticker)
CREATE TABLE IF NOT EXISTS daily_sentiment (
    date TEXT NOT NULL, -- Date formatted as YYYY-MM-DD
    ticker TEXT NOT NULL DEFAULT 'MACRO', -- Ticker symbol or 'MACRO' for broad-market
    sentiment_score REAL NOT NULL CHECK (sentiment_score >= -1.0 AND sentiment_score <= 1.0),
    sentiment_label TEXT NOT NULL CHECK (sentiment_label IN ('bullish', 'bearish', 'neutral')),
    summary TEXT, -- Summary rationale generated by the LLM
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (date, ticker)
);

-- Table to log daily recommendations generated by technical model and filtered by sentiment
CREATE TABLE IF NOT EXISTS daily_recommendations (
    date TEXT NOT NULL, -- Date formatted as YYYY-MM-DD
    ticker TEXT NOT NULL,
    signal_type TEXT NOT NULL DEFAULT 'HOLD' CHECK (signal_type IN ('BUY', 'HOLD', 'SELL')),
    prob_buy REAL, -- Probability of BUY target from ML model
    prob_sell REAL, -- Probability of SELL target
    prob_hold REAL, -- Probability of HOLD target
    sentiment_score REAL, -- Daily overnight sentiment score applied as execution filter
    is_sentiment_passed INTEGER DEFAULT 0 CHECK (is_sentiment_passed IN (0, 1)),
    execution_price REAL, -- Yesterday's closing price
    rationale TEXT, -- Narrative explaining the indicator and sentiment alignment
    PRIMARY KEY (date, ticker)
);

-- Secondary indexes for accelerated query performance
CREATE INDEX IF NOT EXISTS idx_fundamentals_is_healthy ON company_fundamentals(is_healthy);
CREATE INDEX IF NOT EXISTS idx_recommendations_date_prob ON daily_recommendations(date, prob_buy DESC);
CREATE INDEX IF NOT EXISTS idx_recommendations_ticker ON daily_recommendations(ticker);
CREATE INDEX IF NOT EXISTS idx_recommendations_signal ON daily_recommendations(date, signal_type);
CREATE INDEX IF NOT EXISTS idx_daily_sentiment_date ON daily_sentiment(date);

-- =============================================================================
-- ENHANCEMENT TABLES (added 2026-09-30)
-- Portfolio Tracking, Model Benchmarking, Recommendation Audit & Performance
-- =============================================================================

-- Complete snapshot of every recommendation for later evaluation and traceability
CREATE TABLE IF NOT EXISTS recommendation_audit_trail (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    ticker TEXT NOT NULL,
    recommendation TEXT NOT NULL CHECK (recommendation IN ('BUY', 'HOLD', 'SELL')),
    recommendation_score REAL,            -- Composite 0-100 score
    timestamp DATETIME NOT NULL,
    market_price_at_recommendation REAL,
    ml_probability REAL,
    technical_signals TEXT,               -- JSON blob of technical indicator values
    fundamental_signals TEXT,             -- JSON blob of fundamental metrics
    sentiment_signal REAL,               -- Sentiment score at time of recommendation
    risk_factors TEXT,                    -- JSON blob of identified risk factors
    supporting_factors TEXT,             -- JSON blob of key supporting factors
    score_explanation TEXT,              -- Human-readable explanation of score
    model_version TEXT,
    data_timestamp DATETIME,
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP
);

-- User paper-trading positions linked back to recommendations
CREATE TABLE IF NOT EXISTS portfolio_positions (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    ticker TEXT NOT NULL,
    quantity REAL NOT NULL,
    purchase_price REAL NOT NULL,
    purchase_date TEXT NOT NULL,          -- YYYY-MM-DD
    recommendation_audit_id INTEGER,      -- FK to recommendation_audit_trail
    recommendation_score REAL,
    recommendation_type TEXT,
    status TEXT DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'CLOSED')),
    sell_price REAL,
    sell_date TEXT,                       -- YYYY-MM-DD
    notes TEXT,
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (recommendation_audit_id) REFERENCES recommendation_audit_trail(id)
);

-- Structured benchmark results for model comparison
CREATE TABLE IF NOT EXISTS model_benchmark_reports (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    model_name TEXT NOT NULL,
    model_version TEXT,
    dataset_period TEXT,                  -- e.g. "2020-01-01 to 2024-01-01"
    training_period TEXT,
    validation_period TEXT,
    test_period TEXT,
    accuracy REAL,
    precision_score REAL,
    recall_score REAL,
    f1_score REAL,
    roc_auc REAL,
    brier_score REAL,
    directional_accuracy REAL,
    backtested_return REAL,
    max_drawdown REAL,
    sharpe_ratio REAL,
    win_rate REAL,
    total_trades INTEGER,
    training_time_seconds REAL,
    total_samples INTEGER,
    class_distribution TEXT,             -- JSON blob of class counts
    parameters TEXT,                      -- JSON blob of hyperparameters
    feature_importances TEXT,             -- JSON blob
    tickers_used TEXT,                   -- JSON list of tickers used
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP
);

-- Tracks realized performance after each recommendation
CREATE TABLE IF NOT EXISTS recommendation_performance (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    recommendation_audit_id INTEGER NOT NULL UNIQUE,
    ticker TEXT NOT NULL,
    recommendation_date TEXT NOT NULL,    -- YYYY-MM-DD
    recommendation_type TEXT NOT NULL,
    entry_price REAL NOT NULL,
    price_1d REAL,
    price_1w REAL,
    price_1m REAL,
    price_3m REAL,
    return_1d REAL,
    return_1w REAL,
    return_1m REAL,
    return_3m REAL,
    max_gain REAL,
    max_loss REAL,
    is_profitable_1d INTEGER,
    is_profitable_1w INTEGER,
    is_profitable_1m INTEGER,
    is_profitable_3m INTEGER,
    last_evaluated DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (recommendation_audit_id) REFERENCES recommendation_audit_trail(id)
);

-- Indexes for new tables
CREATE INDEX IF NOT EXISTS idx_audit_ticker ON recommendation_audit_trail(ticker);
CREATE INDEX IF NOT EXISTS idx_audit_timestamp ON recommendation_audit_trail(timestamp);
CREATE INDEX IF NOT EXISTS idx_audit_recommendation ON recommendation_audit_trail(recommendation);
CREATE INDEX IF NOT EXISTS idx_portfolio_status ON portfolio_positions(status);
CREATE INDEX IF NOT EXISTS idx_portfolio_ticker ON portfolio_positions(ticker);
CREATE INDEX IF NOT EXISTS idx_benchmark_model ON model_benchmark_reports(model_name, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_rec_perf_ticker ON recommendation_performance(ticker);
CREATE UNIQUE INDEX IF NOT EXISTS idx_rec_perf_audit ON recommendation_performance(recommendation_audit_id);
CREATE INDEX IF NOT EXISTS idx_rec_perf_date ON recommendation_performance(recommendation_date);
